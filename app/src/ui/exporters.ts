import type { RefResult } from '../core/types';
import { toBibtex } from '../core/verify';
import type { ClaimCheck, State } from '../engine/session';
import { SUPPORT, VERDICT, isProblem } from './labels';

export function download(name: string, text: string, type = 'text/plain') {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

export function markdownReport(s: State): string {
  const rs = s.results.filter((r): r is RefResult => !!r);
  const doc = s.doc!;
  const lines: string[] = [];
  lines.push(`# Citation audit: ${s.inputName ?? 'document'}`, '');
  lines.push(`Generated by Veracite on ${new Date().toISOString().slice(0, 10)}. ${rs.length} references checked.`, '');
  const counts = new Map<string, number>();
  for (const r of rs) counts.set(r.verdict, (counts.get(r.verdict) ?? 0) + 1);
  lines.push('| Verdict | Count |', '|---|---|');
  for (const [v, n] of counts) lines.push(`| ${VERDICT[v as keyof typeof VERDICT].label} | ${n} |`);
  lines.push('', '## References needing attention', '');
  for (const r of rs.filter((x) => isProblem(x.verdict))) {
    const pg = doc.refPages?.[r.index];
    lines.push(`### [${r.index + 1}] ${VERDICT[r.verdict].label}${pg ? ` (PDF page ${pg})` : ''}`, '', `> ${r.parsed.raw}`, '');
    for (const c of r.checks.filter((x) => x.status === 'mismatch')) lines.push(`- ${c.field}: cited “${c.cited ?? '—'}”, published record “${c.found ?? '—'}”${c.note ? ` (${c.note})` : ''}`);
    for (const i of r.issues) lines.push(`- ${i}`);
    if (r.suggestedFix) lines.push('', `Suggested correction: ${r.suggestedFix}`);
    lines.push('');
  }
  const done = s.claims.filter((c) => c.status === 'done' && c.label === 'review');
  if (done.length) {
    lines.push('## Citing sentences to review', '', 'The cited passages do not clearly back these sentences. On Citation-Integrity validation data, 76% of sentences flagged this way were confirmed citation errors.', '');
    for (const c of done) {
      const ci = doc.citances[c.citanceId];
      lines.push(`- **${SUPPORT[c.label!].label}** (ref ${c.refIndex + 1}, ${c.sourceKind}): “${ci.claim}”`);
      if (c.evidence[0]) lines.push(`  - Closest evidence: “${c.evidence[0].text}”`);
    }
  }
  return lines.join('\n');
}

export function jsonReport(s: State): string {
  return JSON.stringify(
    {
      tool: 'Veracite',
      date: new Date().toISOString(),
      input: s.inputName,
      references: s.results.map((r) => r && { index: r.index + 1, reference: r.parsed.raw, verdict: r.verdict, confidence: r.confidence, issues: r.issues, checks: r.checks, match: r.match && { title: r.match.title, doi: r.match.doi, arxiv: r.match.arxivId, url: r.match.url, source: r.match.source } }),
      claims: s.claims.map((c: ClaimCheck) => ({ claim: s.doc!.citances[c.citanceId].claim, reference: c.refIndex + 1, status: c.status, label: c.label, probs: c.probs, source: c.sourceKind, evidence: c.evidence.slice(0, 3).map((e) => e.text) })),
    },
    null,
    1,
  );
}

export function correctedBibtex(s: State): string {
  return s.results
    .filter((r): r is RefResult => !!r && !!r.match && (r.verdict === 'verified' || r.verdict === 'verified_minor' || r.verdict === 'metadata_error' || r.verdict === 'retracted'))
    .map((r) => `% [${r.index + 1}] ${VERDICT[r.verdict].label}\n${toBibtex(r.match!)}`)
    .join('\n\n');
}
